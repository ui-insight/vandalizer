"""Static report presentation and provenance for saved workflow output."""
from datetime import datetime, timezone
from html import escape

from bs4 import BeautifulSoup
from markdown_it import MarkdownIt

from app.utils.timestamps import utc_iso


def render_report_markdown(content: str) -> str:
    md = MarkdownIt("commonmark", {"html": False}).enable("table")
    md.renderer.rules["image"] = lambda tokens, idx, *_: escape(tokens[idx].content)
    return f'''<!doctype html><html><head><style>
body{{font:16px/1.6 system-ui,sans-serif;color:#1e293b;max-width:900px;margin:auto;padding:24px}}
table{{display:block;overflow-x:auto;border-collapse:collapse;max-width:100%}}
th,td{{border:1px solid #cbd5e1;padding:8px;text-align:left}}th{{background:#f1f5f9}}
pre{{white-space:pre-wrap;overflow-wrap:anywhere;background:#f8fafc;padding:12px}}
h1,h2,h3{{line-height:1.3}}body{{overflow-wrap:anywhere}}
@media print{{body{{padding:0}}table{{display:table}}}}
</style></head><body>{md.render(content)}</body></html>'''


def workflow_source(db, result: dict, workflow: dict) -> dict:
    """Prefer names snapshotted at execution, not today's renamed sources."""
    config = result.get("run_config") or {}
    name = (config.get("workflow") or {}).get("name") or workflow.get("name") or "Workflow output"
    documents = [doc["title"] for doc in config.get("documents", []) if doc.get("title")]
    if not documents and result.get("document_title"):
        documents = [result["document_title"]]
    if not documents and not config.get("documents"):
        for uuid in (result.get("input_context") or {}).get("doc_uuids") or []:
            doc = db.smart_document.find_one({"uuid": uuid})
            if doc and doc.get("title"):
                documents.append(doc["title"])
    started = result.get("start_time")
    if isinstance(started, str):
        try:
            started = datetime.fromisoformat(started.replace("Z", "+00:00"))
        except ValueError:
            started = None
    return {"workflow_name": name, "document_names": documents,
            "run_started_at": utc_iso(started) if isinstance(started, datetime) else None}


def report_page(html: str, fallback_title: str, source: dict) -> tuple[str, str]:
    soup = BeautifulSoup(html, "html.parser")
    body = soup.body or soup
    heading = body.find(["h1", "h2"])
    if heading is None:
        heading = soup.new_tag("h1")
        heading.string = fallback_title
        body.insert(0, heading)
    title = heading.get_text(" ", strip=True) or fallback_title
    heading.name = "h1"
    line = f'Generated by workflow “{source["workflow_name"]}”'
    if source["document_names"]:
        line += " from " + "; ".join(source["document_names"])
    if source["run_started_at"]:
        started = datetime.fromisoformat(source["run_started_at"]).astimezone(timezone.utc)
        # A downloaded static page has no browser timezone conversion. Label
        # UTC explicitly and use the run date, never the later page-save date.
        line += " on " + started.strftime("%b %d, %Y at %H:%M UTC")
    else:
        line += ". Run date unavailable"
    provenance = soup.new_tag("p", attrs={"class": "workflow-source", "style": "font-size:14px;color:#475569;margin-top:8px"})
    provenance.string = line + "."
    heading.insert_after(provenance)
    return title[:200], str(soup)
