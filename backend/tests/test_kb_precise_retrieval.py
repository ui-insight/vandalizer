class TestIndex:
    def test_every_chunk_is_labelled_by_the_section_holding_most_of_its_text(self):
        index = _index()
        for i, c in enumerate(index.chunks):
            if c["chunk_id"].startswith("subD"):
                text = c["content"]
                spans = {k: text.count(k) for k in ("§ 200.306", "§ 200.307", "§ 200.308")}
                assert index.keys[i] in {"200.306", "200.307", "200.308", "200.309"}
                # A chunk holding nothing but one section's paragraphs is that section's.
                if not any(spans.values()):
                    marker = re.search(r"\((\w)\) (cost sharing|program income|budget revision)", text)
                    if marker:
                        expected = {"cost sharing": "200.306", "program income": "200.307",
                                    "budget revision": "200.308"}[marker.group(2)]
                        assert index.keys[i] == expected
        assert index.section_titles["200.307"] == "Program income"

    def test_a_policy_page_heading_names_its_section(self):
        index = _index()
        keys = {index.keys[i] for i, c in enumerate(index.chunks) if c["chunk_id"].startswith("apm1313")}
        assert keys == {"45.13"}
        assert index.section_titles["45.13"] == "Program Income on Sponsored Projects"

    def test_a_contents_list_is_not_the_sections_but_a_one_line_section_is(self):
        text = (
            "Contents\n§ 200.501 Audit requirements.\n§ 200.506 Audit costs.\n\n"
            "§ 200.501 Audit requirements.\n\n" + _para("a", 600, "single audit threshold") + "\n\n"
            "§ 200.506 Audit costs.\n\nSee § 200.425.\n\n"
            "§ 200.507 Program-specific audits.\n\n" + _para("b", 600, "program-specific audit") + "\n"
        )
        index = kr.build_index(KB, _chunks("subF", "Subpart F", text))
        assert index.section_titles["200.506"] == "Audit costs"
        assert "200.501" in index.keys and "200.507" in index.keys

    def test_appendices_for_other_recipients_are_left_out_for_an_ihe(self):
        index = _index()
        vii = {i for i, k in enumerate(index.keys) if k == "Appendix VII"}
        iii = {i for i, k in enumerate(index.keys) if k == "Appendix III"}
        assert vii and iii
        assert vii <= index.excluded and not (iii & index.excluded)
        assert not _index(institution_type="").excluded

    def test_bm25_ranks_the_chunk_with_the_query_words(self):
        bm = kr.BM25(["costs of alcoholic beverages are unallowable", "travel costs of employees", "equipment"])
        scores = bm.scores("alcoholic beverage")
        assert int(np.argmax(scores)) == 0
        assert scores[2] == 0

    def test_a_store_that_cannot_list_its_chunks_has_no_index(self, precise):
        assert kr.index_for(MagicMock(), KB) is None
        assert kr.index_for(object(), KB) is None


