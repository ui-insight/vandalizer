class TestModelFiles:
    def _pin(self, monkeypatch, files: dict[str, bytes]):
        monkeypatch.setattr(ce, "MODEL_FILES", {n: hashlib.sha256(b).hexdigest() for n, b in files.items()})

    def test_verified_files_are_not_fetched_again(self, tmp_path, monkeypatch):
        self._pin(monkeypatch, {"tokenizer.json": b"{}"})
        (tmp_path / "tokenizer.json").write_bytes(b"{}")
        monkeypatch.setattr(httpx, "stream", MagicMock(side_effect=AssertionError("fetched")))
        assert ce.ensure_model(tmp_path) == tmp_path

    def test_a_download_that_does_not_match_its_hash_is_refused(self, tmp_path, monkeypatch):
        self._pin(monkeypatch, {"onnx/model.onnx": b"the real weights"})
        response = MagicMock()
        response.iter_bytes.return_value = [b"tampered"]
        stream = MagicMock()
        stream.return_value.__enter__.return_value = response
        monkeypatch.setattr(httpx, "stream", stream)
        with pytest.raises(ce.ModelUnavailable, match="failed verification"):
            ce.ensure_model(tmp_path)
        assert not (tmp_path / "onnx" / "model.onnx").exists()
        assert not list((tmp_path / "onnx").glob("*.part"))

    def test_a_missing_file_without_download_is_unavailable(self, tmp_path, monkeypatch):
        self._pin(monkeypatch, {"tokenizer.json": b"{}"})
        with pytest.raises(ce.ModelUnavailable, match="missing"):
            ce.ensure_model(tmp_path, download=False)

    def test_a_failed_load_is_remembered_and_retrieval_degrades(self, monkeypatch):
        monkeypatch.setattr(ce, "_SCORER", None)
        monkeypatch.setattr(ce, "_FAILED", False)
        attempts = MagicMock(side_effect=ce.ModelUnavailable("offline"))
        monkeypatch.setattr(ce, "ensure_model", attempts)
        assert ce.get_cross_encoder() is None
        assert ce.get_cross_encoder() is None
        assert attempts.call_count == 1


class TestScorer:
    """The scorer batches pairs shortest first, so a short passage is not
    padded to a long one, and hands the scores back in the order given."""

    class _Tokenizer:
        def encode_batch(self, pairs):
            lens = [len(q.split()) + len(p.split()) for q, p in pairs]
            width = max(lens)
            return [MagicMock(ids=[1] * n + [0] * (width - n), attention_mask=[1] * n + [0] * (width - n),
                              type_ids=[0] * width) for n in lens]

    class _Session:
        """The score of a pair is its unpadded length."""

        def __init__(self):
            self.widths = []

        def run(self, _outputs, feed):
            self.widths.append(feed["input_ids"].shape[1])
            return [feed["attention_mask"].sum(axis=1, keepdims=True).astype(np.float32)]

    def test_scores_come_back_in_the_order_given(self, monkeypatch):
        monkeypatch.setattr(ce, "BATCH_SIZE", 2)
        scorer = ce.CrossEncoder.__new__(ce.CrossEncoder)
        scorer.tokenizer, scorer.session = self._Tokenizer(), self._Session()
        scorer.input_names = {"input_ids", "attention_mask", "token_type_ids"}
        assert scorer.scores("q", ["a b c d e f", "a", "a b c", "a b", "a b c d e"]) == [7.0, 2.0, 4.0, 3.0, 6.0]
        assert scorer.session.widths == [3, 6, 7]
