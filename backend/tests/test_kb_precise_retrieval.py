def _pool(store, query, k=4):
    return kg._retrieve_pool(store, KB, query, k=k, floor=0.0)


class TestPrecisePool:
    def test_a_question_the_base_cannot_answer_gets_no_passage(self, precise):
        assert _pool(_store(), "parking permits for visitors") == []

    def test_plain_words_reach_the_section_through_its_title(self, precise):
        pool = _pool(_store(), "program income")
        assert pool and pool[0].get("_section") == "200.307"
        assert pool[0]["content"].startswith("§ 200.307 Program income.")

    def test_an_appendix_for_other_recipients_is_never_handed_to_an_ihe(self, precise):
        pool = _pool(_store(), "indirect cost rate negotiated")
        assert pool
        assert not any("Appendix VII" in p["content"] or "vw" in p["content"] for p in pool)

    def test_a_named_long_section_also_gives_the_paragraph_past_its_cap(self, precise):
        pool = _pool(_store(), "200.308 one-time extension period of performance")
        assert pool[0].get("_section") == "200.308"
        assert "One-time extensions" not in pool[0]["content"]   # past the 4,000-character cap
        assert any("One-time extensions" in p["content"] for p in pool[1:])

    def test_a_named_section_stays_whatever_the_reranker_says(self, precise, monkeypatch):
        monkeypatch.setattr(precise, "scores", lambda q, ps: [-20.0] * len(ps))
        pool = _pool(_store(), "200.307")
        assert [p.get("_section") for p in pool][:1] == ["200.307"]

    def test_a_policy_page_named_by_number_is_handed_over_by_its_chunks(self, precise):
        pool = _pool(_store(), "APM 45.13 program income")
        assert pool and all(p["chunk_id"].startswith("apm1313") for p in pool[:2])

    def test_the_pool_is_cached_for_a_fixed_query(self, precise):
        store = _store()
        first = _pool(store, "program income")
        calls = precise.calls
        assert _pool(store, "program income") == first
        assert precise.calls == calls

    def test_without_the_reranker_the_vector_ranking_stands(self, monkeypatch):
        monkeypatch.setenv("KB_PRECISE_RETRIEVAL", "true")
        monkeypatch.setattr(ce, "get_cross_encoder", lambda: None)
        kr._INDEXES.clear()
        kr._RESULTS.clear()
        store = _store()
        pool = _pool(store, "parking permits for visitors")
        assert len(pool) == 4      # the vector ranking always fills its slots
        assert store.vector_calls == 1

    def test_switched_off_it_is_the_vector_ranking(self, precise, monkeypatch):
        monkeypatch.setenv("KB_PRECISE_RETRIEVAL", "false")
        assert len(_pool(_store(), "parking permits for visitors")) == 4

    def test_grounding_says_no_passage_matched(self, precise):
        cfg = kg.GroundingConfig(targets=[kg.KnowledgeBaseTarget(kb_uuid=KB, queries=["parking permits for visitors"])])
        result = kg.retrieve_grounding(cfg, {}, dm=_store())
        assert result.empty
        assert "no matching passages" in result.warnings[0]


