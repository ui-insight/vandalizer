def _chunks(source_id: str, name: str, text: str) -> list[dict]:
    from app.services.document_manager import CHUNK_OVERLAP, CHUNK_SIZE, _split_text_with_offsets

    return [
        {"content": chunk, "metadata": {"source_id": source_id, "source_name": name, "chunk_index": i},
         "chunk_id": f"{source_id}_chunk_{i}", "score": None, "similarity": None}
        for i, (chunk, _) in enumerate(_split_text_with_offsets(text, CHUNK_SIZE, CHUNK_OVERLAP))
    ]


_WORD_RE = re.compile(r"[a-z0-9]+")


def _bag(text: str) -> np.ndarray:
    """A deterministic bag-of-words vector: what a fake embedder returns."""
    v = np.zeros(256, dtype=np.float32)
    for w in _WORD_RE.findall(text.lower()):
        v[int(hashlib.md5(w.encode(), usedforsecurity=False).hexdigest(), 16) % 256] += 1.0
    n = float(np.linalg.norm(v))
    return v / n if n else v


class FakeEmbedder:
    def __call__(self, texts):
        return [_bag(t) for t in texts]


class Store:
    """The DocumentManager reads retrieval uses, over in-memory chunks."""

    def __init__(self, *sources):
        self.chunks = [c for s in sources for c in s]
        self.embedding_function = FakeEmbedder()
        self.vector_calls = 0

    def query_kb(self, kb_uuid, query, k=8, min_similarity=0.0, **kw):
        self.vector_calls += 1
        q = _bag(query)
        scored = sorted(((float(_bag(c["content"]) @ q), c) for c in self.chunks), key=lambda x: -x[0])
        return [dict(c, similarity=s) for s, c in scored[:k] if s >= min_similarity]

    def get_kb_chunks_containing(self, kb_uuid, substring, limit=20):
        return [dict(c) for c in self.chunks if substring in c["content"]][:limit]

    def get_kb_chunks_by_ids(self, kb_uuid, ids):
        by = {c["chunk_id"]: c for c in self.chunks}
        return [dict(by[i]) for i in ids if i in by]

    def get_kb_all_chunks(self, kb_uuid, limit=50_000):
        return [dict(c) for c in self.chunks]

    def get_kb_collection_readonly(self, kb_uuid):
        return MagicMock(count=MagicMock(return_value=len(self.chunks)))


class FakeScorer:
    """Scores a pair by how many of the query's words the passage holds:
    -9 for none, up to +7 for all. Counts its calls."""

    def __init__(self):
        self.calls = 0

    def scores(self, query, passages):
        self.calls += 1
        words = {w for w in _WORD_RE.findall(query.lower()) if len(w) > 3}
        out = []
        for p in passages:
            have = {w for w in _WORD_RE.findall(p.lower())}
            frac = len(words & have) / len(words) if words else 0.0
            out.append(-9.0 + 16.0 * frac)
        return out


