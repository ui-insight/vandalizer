"""Workflow reports keep their title and run provenance in saved/downloaded HTML."""
from datetime import datetime
from types import SimpleNamespace
from unittest.mock import AsyncMock, patch

import pytest
from bs4 import BeautifulSoup

from app.schemas.chat_export import ChatExportRequest
from app.services import artifacts
from app.services.chat_export import render_chat_export
from tests.test_artifacts import Collection, db as db, route_env as route_env
from tests.test_chat_routes import _auth


REPORT = "Subaward Review Summary – WSU-UI-2025-1132"


def result(output=None):
    return {"workflow": "wf1", "session_id": "run1", "status": "completed",
            "start_time": datetime(2026, 10, 29, 22, 28),
            "run_config": {"workflow": {"name": "Subaward Review Summary v2"},
                           "documents": [{"uuid": "doc1", "title": "NIH subaward agreement.pdf"}]},
            "final_output": {"output": output if output is not None else f"# {REPORT}\n\n## Findings\n\nReviewed agreement.\n\n| Term | Value |\n| --- | --- |\n| Award | $25,000 |"}}


@pytest.mark.asyncio
async def test_save_open_and_download_start_with_report_and_run_source(client, db, route_env):
    db.workflow.docs.append({"_id": "wf1", "name": "Renamed since the run"})
    cookies, headers = _auth()
    with patch("app.services.workflow_service._get_authorized_workflow_result", AsyncMock(return_value=SimpleNamespace(model_dump=result))):
        saved = await client.post("/api/pages/from-workflow/run1", cookies=cookies, headers=headers)
    assert saved.status_code == 200
    page = saved.json()
    assert page["title"] == REPORT
    assert page["source"]["workflow_name"] == "Subaward Review Summary v2"
    assert page["source"]["run_started_at"] == "2026-10-29T22:28:00+00:00"
    expected = 'Generated by workflow “Subaward Review Summary v2” from NIH subaward agreement.pdf on Oct 29, 2026 at 22:28 UTC.'
    for download in (False, True):
        response = await client.get(f'/api/pages/{page["uuid"]}/revisions/{page["latest_revision"]}/content',
                                    params={"download": str(download).lower()}, cookies=cookies)
        assert response.status_code == 200
        soup = BeautifulSoup(response.text, "html.parser")
        assert soup.body.find(["h1", "h2"]).get_text() == REPORT
        assert soup.h1.find_next_sibling("p").get_text() == expected
        assert soup.select_one("table td").get_text() == "Award"
        assert "Chat export" not in soup.get_text()
        assert "Assistant" not in [h.get_text() for h in soup.select("h1,h2,h3")]
        if download:
            assert "attachment" in response.headers["content-disposition"]


@pytest.mark.parametrize("output", [
    f'<!doctype html><html><head><style>.value{{color:green}}</style></head><body><main><h1>{REPORT}</h1><p class="value">Reviewed agreement.</p></main></body></html>',
    f'```html\n<article><h1>{REPORT}</h1><p>Reviewed agreement.</p></article>\n```',
    f'## {REPORT}\n\nReviewed agreement.',
])
def test_authored_report_title_and_content_survive(db, output):
    doc = artifacts.from_workflow(db, result(output), "testuser")
    soup = BeautifulSoup(artifacts.revision(doc)["html"], "html.parser")
    assert doc["title"] == REPORT
    assert len(soup.select("h1")) == 1
    assert soup.h1.get_text() == REPORT
    assert len(soup.select(".workflow-source")) == 1
    assert "Reviewed agreement." in soup.get_text()
    if "<style>" in output:
        assert ".value{color:green}" in soup.style.get_text()


@pytest.mark.parametrize("output", ["Plain result without a heading.", [{"Amount": 25}], {"Risk": "Low"}])
def test_unheaded_and_structured_results_have_a_workflow_title(db, output):
    doc = artifacts.from_workflow(db, result(output), "testuser")
    soup = BeautifulSoup(artifacts.revision(doc)["html"], "html.parser")
    assert soup.h1.get_text() == "Subaward Review Summary v2"
    assert soup.h1.find_next_sibling("p")["class"] == ["workflow-source"]
    assert "Chat export" not in soup.get_text()
    if isinstance(output, list):
        assert soup.td.get_text() == "25"


def test_legacy_inputs_multiple_sources_and_missing_date_are_honest(db):
    run = result()
    run.pop("run_config")
    run.pop("start_time")
    run["input_context"] = {"doc_uuids": ["one", "two", "deleted"]}
    db.smart_document = Collection()
    db.smart_document.docs = [{"uuid": "one", "title": "Agreement.pdf"}, {"uuid": "two", "title": "Budget.xlsx"}]
    db.workflow.docs.append({"_id": "wf1", "name": "Legacy review"})
    doc = artifacts.from_workflow(db, run, "testuser")
    soup = BeautifulSoup(artifacts.revision(doc)["html"], "html.parser")
    assert soup.select_one(".workflow-source").get_text() == 'Generated by workflow “Legacy review” from Agreement.pdf; Budget.xlsx. Run date unavailable.'


def test_source_names_are_text_and_retry_preserves_saved_page(db):
    run = result()
    run["run_config"]["workflow"]["name"] = '<img src=x onerror="steal()">'
    run["run_config"]["documents"][0]["title"] = "<script>secret()</script>.pdf"
    first = artifacts.from_workflow(db, run, "testuser")
    soup = BeautifulSoup(artifacts.revision(first)["html"], "html.parser")
    assert not soup.select("script,img")
    assert '<script>secret()</script>.pdf' in soup.select_one(".workflow-source").get_text()
    revised = artifacts.revise(db, first, "Edited report", "<h1>Edited report</h1>", first["latest_revision"])
    published = artifacts.publish(db, revised, revised["latest_revision"])
    run["run_config"]["workflow"]["name"] = "Renamed"
    assert artifacts.from_workflow(db, run, "testuser") == published
    assert len(db.html_artifacts.docs) == 1


