export interface EstimateInput {
  counts: OperationCounts
  inputPerMTok: number
  outputPerMTok: number
  /** Users on the deployment. */
  users: number
  /**
   * Share of input tokens served from the provider's prompt cache, 0–1. Repeated
   * document and knowledge-base context is highly cacheable; cached reads bill at
   * roughly a tenth of the standard input rate.
   */
  cacheHitRate?: number
  operations?: Operation[]
}

export interface OperationEstimate {
  operation: Operation
  count: number
  inputTokens: number
  outputTokens: number
  cost: number
}

export interface Estimate {
  perOperation: OperationEstimate[]
  inputTokens: number
  outputTokens: number
  costPerUser: number
  costTotal: number
}

/** Cached input tokens bill at ~10% of the standard input rate. */
const CACHE_READ_MULTIPLIER = 0.1

const clamp01 = (n: number) => Math.min(1, Math.max(0, n))

/** Non-finite or negative inputs collapse to 0 so a half-typed field can't produce NaN. */
const safe = (n: number) => (Number.isFinite(n) && n > 0 ? n : 0)

export function estimate({
  counts,
  inputPerMTok,
  outputPerMTok,
  users,
  cacheHitRate = 0,
  operations = OPERATIONS,
}: EstimateInput): Estimate {
  const hitRate = clamp01(safe(cacheHitRate))
  const inRate = safe(inputPerMTok)
  const outRate = safe(outputPerMTok)
  // Blended input rate: the cached share bills at the discounted read rate.
  const effectiveInRate = inRate * (1 - hitRate) + inRate * CACHE_READ_MULTIPLIER * hitRate

  const perOperation = operations.map((operation) => {
    const count = Math.round(safe(counts[operation.id] ?? 0))
    const inputTokens = count * operation.inputTokens
    const outputTokens = count * operation.outputTokens
    return {
      operation,
      count,
      inputTokens,
      outputTokens,
      cost: (inputTokens / 1e6) * effectiveInRate + (outputTokens / 1e6) * outRate,
    }
  })

  const inputTokens = perOperation.reduce((sum, r) => sum + r.inputTokens, 0)
  const outputTokens = perOperation.reduce((sum, r) => sum + r.outputTokens, 0)
  const costPerUser = perOperation.reduce((sum, r) => sum + r.cost, 0)

  return {
    perOperation,
    inputTokens,
    outputTokens,
    costPerUser,
    costTotal: costPerUser * Math.max(0, Math.round(safe(users))),
  }
}

export function formatUsd(value: number): string {
  if (!Number.isFinite(value)) return '$0.00'
  if (value > 0 && value < 0.01) return '<$0.01'
  return value.toLocaleString('en-US', {
    style: 'currency',
    currency: 'USD',
    maximumFractionDigits: value >= 100 ? 0 : 2,
  })
}

export function formatTokens(value: number): string {
  if (!Number.isFinite(value) || value <= 0) return '0'
  if (value >= 1e9) return `${(value / 1e9).toFixed(1)}B`
  if (value >= 1e6) return `${(value / 1e6).toFixed(1)}M`
  if (value >= 1e3) return `${(value / 1e3).toFixed(0)}K`
  return String(Math.round(value))
}
