/**
 * Cost model behind the Docs → Cost Estimator section.
 *
 * The numbers here are *starting assumptions*, not measurements. Every LLM call
 * in the app is metered at a single chokepoint (MeteredModel → record_usage) and
 * written to the `llm_usage` collection with a `feature` label, so a deployment
 * with real traffic should calibrate these defaults against its own ledger
 * rather than trusting them. The operation ids below deliberately mirror the
 * metering feature names used in the backend.
 */

export interface Operation {
  /** Matches the `feature` label written to the llm_usage ledger. */
  id: string
  label: string
  /** What one unit of this operation is. */
  unit: string
  description: string
  /** Prompt tokens for one operation, including re-sent context. */
  inputTokens: number
  /** Completion tokens for one operation. */
  outputTokens: number
}

