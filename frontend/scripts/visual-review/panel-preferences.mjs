import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { createReview } from './harness.mjs'
const review=await createReview({output:process.env.REVIEW_OUTPUT,baseURL:process.env.REVIEW_BASE_URL,resetStorage:false})
const {page}=review
page.setDefaultTimeout(15000)
const divider=()=>page.getByRole('separator',{name:'Resize workspace panels'})
const sources=()=>page.getByRole('region',{name:'Workspace source panel',exact:true})
const tools=()=>page.getByRole('region',{name:'Tools and assistant',exact:true})
const nav=()=>page.getByRole('navigation',{name:'Workspace navigation'})
async function shot(id){
 await review.capture(id)
 assert.ok(review.captures.at(-1).pageWidth<=review.captures.at(-1).viewport.width,id+': overflow')
 assert.deepEqual(JSON.parse(await readFile(resolve(review.out,id+'.axe.json'),'utf8')),[],id+': accessibility')
 console.log('Captured '+id)
}
try {
 await page.setViewportSize({width:1440,height:900});await page.goto(review.baseURL+'/?mode=files&tab=library')
 await divider().waitFor()
 await page.evaluate(()=>{localStorage.setItem('workspace:panelSplit','Infinity');localStorage.setItem('workspace:railDocked','false')})
 await page.reload();await divider().waitFor()
 assert.equal(Number(await divider().getAttribute('aria-valuenow')),60)
 await shot('panels-invalid-preference-1440')
 await divider().focus();await page.keyboard.press('Home')
 assert.ok(Math.abs((await sources().boundingBox()).width-280)<2)
 await page.keyboard.press('End')
 const preference=await page.evaluate(()=>localStorage.getItem('workspace:panelSplit'))
 const wideValue=await divider().getAttribute('aria-valuenow')
 assert.ok((await tools().boundingBox()).width>=319)
 await shot('panels-keyboard-resize-1440')
 await page.reload();await divider().waitFor()
 assert.equal(await divider().getAttribute('aria-valuenow'),wideValue)
 await shot('panels-restored-split-1440')
 await page.setViewportSize({width:800,height:600})
 await page.waitForFunction(()=>document.querySelector('#main-content').getBoundingClientRect().width>650)
 assert.ok((await tools().boundingBox()).width>=319)
 assert.ok((await sources().boundingBox()).width>=279)
 assert.equal(await page.evaluate(()=>localStorage.getItem('workspace:panelSplit')),preference)
 await shot('panels-fitted-split-800')
 const expand=page.getByRole('button',{name:'Expand activity',exact:true})
 await expand.focus();await page.keyboard.press('Enter')
 const activity=page.getByRole('dialog',{name:'Activity',exact:true})
 await activity.waitFor();await page.waitForFunction(()=>document.activeElement.id==='close-workspace-activity')
 for(let i=0;i<10;i++){await page.keyboard.press('Tab');assert.equal(await activity.evaluate(e=>e.contains(document.activeElement)),true)}
 await shot('panels-activity-drawer-800')
 await page.keyboard.press('Escape');await activity.waitFor({state:'hidden'})
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Expand activity')
 assert.equal(await page.evaluate(()=>localStorage.getItem('workspace:railDocked')),'false')
 await page.setViewportSize({width:1440,height:900})
 await page.waitForFunction(()=>document.querySelector('#main-content').getBoundingClientRect().width<1200)
 assert.equal(await divider().getAttribute('aria-valuenow'),wideValue)
 await shot('panels-wide-preference-retained-1440')

 await page.setViewportSize({width:320,height:568})
 await page.getByRole('button',{name:'Files panel',exact:true}).waitFor()
 assert.equal(await divider().count(),0)
 assert.equal(await page.getByRole('button',{name:'Show files beside chat',exact:true}).count(),0)
 await page.getByRole('button',{name:'Open Library panel',exact:true}).click()
 await page.getByRole('button',{name:'Mine',exact:true}).waitFor()
 await shot('panels-mobile-library-320')
 await nav().getByRole('button',{name:'Knowledge',exact:true}).click()
 await page.getByRole('tab',{name:'Mine',exact:true}).waitFor()
 await page.getByRole('button',{name:'Open Assistant panel',exact:true}).click()
 const input=page.getByRole('textbox',{name:'Message input'})
 await input.fill('Keep this draft while changing panes')
 await nav().getByRole('button',{name:'Files',exact:true}).click()
 assert.equal(await input.inputValue(),'Keep this draft while changing panes')
 assert.equal(await page.getByRole('button',{name:'Open Assistant panel',exact:true}).getAttribute('aria-pressed'),'true')
 await shot('panels-mobile-section-return-320')
 await page.getByRole('button',{name:'Files panel',exact:true}).click()
 await page.reload();await page.getByRole('button',{name:'Files panel',exact:true}).waitFor()
 assert.equal(await page.getByRole('button',{name:'Files panel',exact:true}).getAttribute('aria-pressed'),'true')
 await shot('panels-mobile-reload-320')
 await nav().getByRole('button',{name:'Knowledge',exact:true}).click()
 assert.equal(await page.getByRole('button',{name:'Open Assistant panel',exact:true}).getAttribute('aria-pressed'),'true')
 await page.getByRole('button',{name:'Open activity',exact:true}).click();await activity.waitFor()
 await shot('panels-mobile-activity-320')
 await page.keyboard.press('Escape');await activity.waitFor({state:'hidden'})
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Open activity')
 await page.getByRole('button',{name:'Open activity',exact:true}).click();await activity.waitFor()
 await activity.getByRole('button',{name:'New chat',exact:true}).focus();await page.keyboard.press('Enter')
 await activity.waitFor({state:'hidden'})
 await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='Message input')
 await shot('panels-activity-new-chat-320')

 await page.setViewportSize({width:800,height:600})
 await page.goto(review.baseURL+'/?project=project-1&mode=files&tab=library')
 await page.getByRole('button',{name:'Manage project',exact:true}).waitFor()
 assert.equal(await page.locator('.project-context-bar').evaluate(e=>getComputedStyle(e).marginRight),'64px')
 await shot('panels-project-context-fit-800')

 await page.setViewportSize({width:1440,height:900});await nav().getByRole('button',{name:'Files',exact:true}).click()
 await divider().waitFor()
 await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new Error('Storage disabled for review')}})
 await divider().focus();await page.keyboard.press('Home')
 assert.ok(Math.abs((await sources().boundingBox()).width-280)<2)
 await page.getByRole('button',{name:'Collapse activity',exact:true}).click()
 await nav().getByRole('button',{name:'Knowledge',exact:true}).click()
 await page.getByRole('tab',{name:'Mine',exact:true}).waitFor()
 await shot('panels-storage-unavailable-1440')
 assert.deepEqual(review.errors,[]);assert.deepEqual([...review.unmatched],[])
 review.observations.push('Invalid and persisted split values; keyboard bounds; 1440 → 800 → 1440 preference fitting; temporary Activity drawer focus and return; 320 per-section pane choices, draft retention and reload; storage-unavailable navigation. Synthetic API. Source and Library workflow regression uses its separate recipe.')
} catch(error){await review.capture('panel-preferences-blocked',String(error));throw error}
finally{await review.flush();await review.browser.close()}
